export function getSourceById(sourceId) {
  return SOURCES_REGISTRY.find(s => s.id === sourceId) || null;
}

export function getSourcesByCategory(category) {
  if (!category || category === 'ALL') return SOURCES_REGISTRY;
  return SOURCES_REGISTRY.filter(s => s.category.toUpperCase().includes(category.toUpperCase()) || s.type.toUpperCase() === category.toUpperCase());
}

export function getSourcesByType(type) {
  if (!type || type === 'ALL') return SOURCES_REGISTRY;
  return SOURCES_REGISTRY.filter(s => s.type.toLowerCase() === type.toLowerCase());
}

export function getOriginalWorkSources() {
  return SOURCES_REGISTRY.filter(s => s.type === 'bluegun_original');
}

export function getThirdPartySources() {
  return SOURCES_REGISTRY.filter(s => s.type !== 'bluegun_original');
}

export function getUnverifiedSources() {
  return SOURCES_REGISTRY.filter(s => s.status === 'REVIEW REQUIRED' || s.status === 'UNVERIFIED' || s.status === 'SOURCE VERIFICATION REQUIRED');
}

export function getSourcesCount() {
  const all = SOURCES_REGISTRY;
  return {
    total: all.length,
    original: all.filter(s => s.type === 'bluegun_original').length,
    thirdParty: all.filter(s => s.type !== 'bluegun_original').length,
    verified: all.filter(s => s.status === 'VERIFIED' || s.status === 'BLUEGUN ORIGINAL').length,
    reviewRequired: all.filter(s => s.status === 'REVIEW REQUIRED').length,
    images: all.filter(s => s.type === 'image').length,
    libraries: all.filter(s => s.type === 'library').length,
    fonts: all.filter(s => s.type === 'font').length,
  };
}